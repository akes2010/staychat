#!/usr/bin/env bash
# deploy/setup-vps.sh — run ONCE on the VPS (as root or a sudo user).
# Usage:  bash deploy/setup-vps.sh
#
# What it does:
#   1. Installs Docker + Compose plugin if missing
#   2. Creates /opt/staychat-os/.env with strong random secrets (only once —
#      re-runs never overwrite existing secrets)
#   3. Opens firewall ports 80/443 (22 stays open)
#   4. Brings the stack up: app + Caddy (automatic HTTPS for staychat.akmustech.com)
#
# Prerequisites:
#   - DNS: an A record for staychat.akmustech.com → this server's IPv4
#     (set it in the Contabo panel before running, cert issuance needs it)
#   - This script lives inside the cloned repo at /opt/staychat-os
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$APP_DIR/.env"
DOMAIN="staychat.akmustech.com"

echo "── StayChat OS VPS setup ──────────────────────────────────"

# 1. Docker
if ! command -v docker >/dev/null 2>&1; then
  echo "→ Installing Docker…"
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
else
  echo "✓ Docker $(docker --version | cut -d' ' -f3 | tr -d ',')"
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "→ Installing Docker Compose plugin…"
  apt-get update -qq && apt-get install -y -qq docker-compose-plugin
fi

# 2. Secrets (only generated once — re-runs keep the existing .env)
if [ ! -f "$ENV_FILE" ]; then
  echo "→ Generating secrets into $ENV_FILE"
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/setup-vps.sh — keep this file secret. Never commit it.
JWT_ACCESS_SECRET=$(openssl rand -hex 48)
JWT_REFRESH_SECRET=$(openssl rand -hex 48)
COOKIE_SECRET=$(openssl rand -hex 32)
CREDENTIALS_ENCRYPTION_KEY=$(openssl rand -hex 32)
RESEND_API_KEY=
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
SMTP_FROM=StayChat OS <support@akmustech.com>
EMAIL_FROM=StayChat OS <support@akmustech.com>
PLATFORM_GATEWAY=stripe
EOF
  chmod 600 "$ENV_FILE"
  echo "✓ Secrets written (chmod 600)"
else
  echo "✓ .env already exists — keeping existing secrets"
fi

# 3. Firewall (best-effort across ufw / plain iptables)
if command -v ufw >/dev/null 2>&1; then
  echo "→ ufw: allowing 22, 80, 443"
  ufw allow 22/tcp  >/dev/null 2>&1 || true
  ufw allow 80/tcp  >/dev/null 2>&1 || true
  ufw allow 443/tcp >/dev/null 2>&1 || true
else
  echo "→ ufw not found — make sure ports 80 and 443 are open in the Contabo panel firewall"
fi

# 4. DNS sanity check (warn only — Caddy will retry regardless)
IP=$(curl -s -4 https://ifconfig.me || true)
DNSIP=$(getent hosts "$DOMAIN" | awk '{print $1}' | head -1 || true)
if [ -n "$IP" ] && [ -n "$DNSIP" ] && [ "$IP" != "$DNSIP" ]; then
  echo "⚠ WARNING: $DOMAIN resolves to $DNSIP but this server looks like $IP"
  echo "  Fix the A record in the Contabo panel or Let's Encrypt issuance will fail."
fi

# 5. Build + start
cd "$APP_DIR"
echo "→ Building the app image (first run takes a few minutes)…"
docker compose -f deploy/docker-compose.prod.yml build
echo "→ Starting app + Caddy…"
docker compose -f deploy/docker-compose.prod.yml up -d
echo "→ Waiting for health…"
for i in $(seq 1 30); do
  sleep 3
  if curl -sf http://localhost:3000/api/health >/dev/null 2>&1 \
     || docker exec staychat wget -qO- http://localhost:3000/api/health >/dev/null 2>&1; then
    echo "✓ App is healthy"
    break
  fi
  [ "$i" = 30 ] && { echo "✗ App did not become healthy — check: docker compose -f deploy/docker-compose.prod.yml logs staychat"; exit 1; }
done

# 6. Daily database backups (cron — 03:17, keeps 14 days)
if command -v crontab >/dev/null 2>&1; then
  CRON_LINE="17 3 * * * $APP_DIR/deploy/backup-db.sh >> /var/log/staychat-backup.log 2>&1"
  if crontab -l 2>/dev/null | grep -qF "backup-db.sh"; then
    echo "✓ Backup cron already installed"
  else
    (crontab -l 2>/dev/null; echo "$CRON_LINE") | crontab -
    echo "✓ Daily DB backup scheduled (03:17, keeps 14 days in /opt/backups)"
  fi
else
  echo "⚠ crontab not found — install cron and add: 17 3 * * * $APP_DIR/deploy/backup-db.sh"
fi

cat <<EOF

──────────────────────────────────────────────────────────────
✓ StayChat OS is live

  Site:      https://$DOMAIN   (certificate auto-issued on first visit;
             give it ~1 minute after the DNS record is set)
  Local:     http://localhost:3000 (health: /api/health)

  Demo logins (demo data was seeded):  password Demo@123456
    superadmin@staychat.io   — platform console (plans, tenants, billing)
    admin@hospitally.com     — demo hotel admin

  Useful commands (in /opt/staychat-os):
    docker compose -f deploy/docker-compose.prod.yml logs -f staychat   # app logs
    docker compose -f deploy/docker-compose.prod.yml restart staychat   # restart
    docker compose -f deploy/docker-compose.prod.yml up -d --build      # deploy new code
    deploy/backup-db.sh                                                 # manual DB backup
    bash deploy/check-deployment.sh                                     # full health report

  Next steps:
    1. Visit https://$DOMAIN — Caddy obtains the TLS certificate automatically.
    2. Log in as superadmin, change the demo passwords (Users → reset),
       or re-seed clean later (see deploy/SETUP.md).
    3. Super Admin → Billing & Approvals → paste your Stripe/Paystack key
       to automate plan payments.
    4. Add RESEND_API_KEY (or SMTP creds) to .env, then:
       docker compose -f deploy/docker-compose.prod.yml up -d
──────────────────────────────────────────────────────────────
EOF
